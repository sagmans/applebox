import AppKit

extension NSPasteboard.PasteboardType {
    /// Clipboard history should track user copies, rather than generated replays.
    nonisolated static let generatedClipboardContent = Self("org.nspasteboard.AutoGeneratedType")
    /// Bundle id the writer declares as the clip's origin (nspasteboard.org convention). It names the
    /// copying app even when focus moved before the next poll, and replays carry it to keep a clip's origin.
    nonisolated static let clipSource = Self("org.nspasteboard.source")
}

/// Distinguish permission prompts from a policy that forbids background reads.
public nonisolated enum ClipboardReadAccess {
    case allowed
    case mayPrompt
    case denied
}

/// Protocol abstracting NSPasteboard operations for testability
public protocol PasteboardProtocol {
    /// The receiver's change count
    var changeCount: Int { get }

    /// Check the current policy without touching the clipboard contents.
    var readAccess: ClipboardReadAccess { get }

    /// Check privacy markers without asking the owner to supply the payload.
    var types: [NSPasteboard.PasteboardType]? { get }

    /// Returns a string for the specified type from the first item in the pasteboard
    func string(forType dataType: NSPasteboard.PasteboardType) -> String?

    /// Returns data for the specified type from the first item in the pasteboard
    func data(forType dataType: NSPasteboard.PasteboardType) -> Data?

    /// Return the ownership count so delayed paste can reject a replacement clipboard. `source` is the
    /// clip's original app, declared on the pasteboard so the clip keeps its origin after a replay.
    func replayData(_ data: Data, forType dataType: NSPasteboard.PasteboardType, source: String?) -> Int?
}
